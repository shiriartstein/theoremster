#!/usr/bin/env python3
"""Build site/cards.js from data/theorems.xlsx.

Usage:  python3 tools/build_cards.py
Needs:  pip install openpyxl

Columns are found by their header names on the "Theorems" sheet, so columns can
be reordered or added freely. Rows marked "Drop" in the "Verified?" column are
left out. Rows marked "Yes" are flagged as verified, which the game can use as
a deck filter. The script stops with a list of problems if any row is invalid.
"""
import json
import re
import sys
from pathlib import Path

from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'data' / 'theorems.xlsx'
TARGET = ROOT / 'site' / 'cards.js'

COLUMNS = {
    'id': 'ID',
    'name': 'Theorem',
    'statement': 'Card front (statement)',
    'prover': 'Proved by',
    'year': 'Year (for sorting)',
    'shown': 'Year on card',
    'area': 'Area',
    'level': 'Level',
    'note': 'Notes / twist',
    'verified': 'Verified?',
}
REQUIRED = ['id', 'name', 'statement', 'prover', 'year', 'shown']

# Notes are shown to players when a card is revealed. These remove sentences
# that were written for the person checking the list rather than for players.
EDITORIAL = [
    re.compile(r'\s*Decide which names? counts?\.', re.I),
    re.compile(r'[;,]?\s*[Ee]ither name (should|could) count\.?'),
]


def clean(value):
    return re.sub(r'\s+', ' ', str(value)).strip() if value is not None else ''


def player_note(note):
    twist = note.lower().startswith('twist card:')
    if twist:
        note = note[len('twist card:'):].strip()
    for pattern in EDITORIAL:
        note = pattern.sub('', note).strip()
    if note and note[-1] not in '.!?)':
        note += '.'
    if note:
        note = note[0].upper() + note[1:]
    return twist, note


def main():
    if not SOURCE.exists():
        sys.exit(f'Missing {SOURCE.relative_to(ROOT)}: put the spreadsheet there.')
    sheet = load_workbook(SOURCE, data_only=True)['Theorems']
    rows = sheet.iter_rows(values_only=True)
    header = [clean(h) for h in next(rows)]
    missing = [title for key, title in COLUMNS.items() if title not in header and key in REQUIRED]
    if missing:
        sys.exit('The Theorems sheet is missing these columns: ' + ', '.join(missing))
    index = {key: header.index(title) for key, title in COLUMNS.items() if title in header}

    cards, problems, seen, dropped = [], [], set(), 0
    for line, row in enumerate(rows, start=2):
        get = lambda key: clean(row[index[key]]) if key in index and index[key] < len(row) else ''
        if not any(clean(v) for v in row):
            continue
        if get('verified').lower() == 'drop':
            dropped += 1
            continue
        empty = [COLUMNS[key] for key in REQUIRED if not get(key)]
        if empty:
            problems.append(f'Row {line}: empty ' + ', '.join(empty))
            continue
        card_id = get('id')
        if card_id in seen:
            problems.append(f'Row {line}: ID {card_id} is used twice')
            continue
        seen.add(card_id)
        try:
            year = int(float(get('year')))
        except ValueError:
            problems.append(f'Row {line}: "{get("year")}" is not a whole year (use negative numbers for BC)')
            continue
        twist, note = player_note(get('note'))
        cards.append({
            'id': card_id,
            'name': get('name'),
            'statement': get('statement'),
            'provers': [p.strip() for p in get('prover').split(' / ') if p.strip()],
            'year': year,
            'shown': get('shown'),
            'area': get('area'),
            'level': get('level'),
            'twist': twist,
            'note': note,
            'verified': get('verified').lower() == 'yes',
        })

    if problems:
        sys.exit('Fix these rows in data/theorems.xlsx:\n  ' + '\n  '.join(problems))
    cards.sort(key=lambda c: (c['year'], c['id']))
    TARGET.write_text(
        '// Generated by tools/build_cards.py from data/theorems.xlsx. Do not edit by hand.\n'
        'window.THEOREM_CARDS = ' + json.dumps(cards, ensure_ascii=False, indent=1) + ';\n',
        encoding='utf-8')
    verified = sum(c['verified'] for c in cards)
    print(f'{len(cards)} cards written to site/cards.js ({verified} verified, {dropped} dropped).')


if __name__ == '__main__':
    main()
